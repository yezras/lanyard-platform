#!/usr/bin/env node
/**
 * Regenerates src/catalog.generated.ts from contracts/connectors-v1/catalog.json.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const repoRoot = join(pkgRoot, "../../..");
const catalogPath = join(repoRoot, "contracts/connectors-v1/catalog.json");
const outPath = join(pkgRoot, "src/catalog.generated.ts");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const json = JSON.stringify(catalog, null, 2);

const source = `/** Generated from contracts/connectors-v1/catalog.json. Do not edit. */
/** Regenerated by: node portal/packages/connectors/scripts/generate-catalog.mjs */

export const CONNECTOR_CATALOG = ${json} as const;

export type ConnectorCatalog = typeof CONNECTOR_CATALOG;
`;

writeFileSync(outPath, source);
process.stdout.write(`wrote ${outPath}\n`);
